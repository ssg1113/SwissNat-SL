/**
 * Mobile Web Share API: Shares .xls NAT file via WhatsApp, Telegram, Gmail, etc.
 */
export async function shareNatFile(
  records: NatRecord[],
  filename = 'Nat_File.xls',
  templateWorkbook?: XLSX.WorkBook | null
): Promise<boolean> {
  const blob = generateNatXlsBlob(records, templateWorkbook);
  const file = new File([blob], filename, { type: 'application/vnd.ms-excel' });

  if (navigator.canShare && navigator.canShare({ files: [file] })) {
    try {
      await navigator.share({
        files: [file],
        title: 'Swiss-Manager NAT File',
        text: `Swiss-Manager NAT file containing ${records.length} cleaned players.`,
      });
      return true;
    } catch (err: any) {
      if (err.name !== 'AbortError') {
        console.error('Share failed:', err);
      }
      return false;
    }
  } else {
    // Fallback: download directly
    downloadBlob(blob, filename);
    return false;
  }
}
