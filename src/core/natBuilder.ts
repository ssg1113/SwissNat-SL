/**
 * Loads the bundled official template from src/assets/Nat File - Last Name & First Name.xls
 */
export function getDefaultNatTemplateWorkbook(): XLSX.WorkBook {
  const binary = atob(DEFAULT_NAT_TEMPLATE_BASE64);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) {
    bytes[i] = binary.charCodeAt(i);
  }
  return XLSX.read(bytes, { type: 'array' });
}

/**
 * Builds an XLSX Workbook containing Sheet 1 (Nat) and Sheet 2 (Help)
 */
export function buildNatWorkbook(records: NatRecord[]): XLSX.WorkBook {
  const template = getDefaultNatTemplateWorkbook();
  const wb = XLSX.utils.book_new();

  // Build rows for Sheet 1 (Nat) with exact 13 columns
  const natData: (string | number)[][] = [
    NAT_HEADERS,
    ...records.map(record => [
      record.ID_No,
      record.LastName,
      record.FirstName,
      record.Sex,
      record.Fed,
      record.Clubnumber,
      record.ClubName,
      record.Birthday,
      record.Rtg_Nat,
      record.Fide_No,
      record.Rtg_Int,
      record.Title,
      record.K,
    ]),
  ];

  const wsNat = XLSX.utils.aoa_to_sheet(natData);

  // Swiss-Manager standard column widths
  wsNat['!cols'] = [
    { wch: 8 },  // Col 0: ID_No
    { wch: 18 }, // Col 1: Last Name
    { wch: 22 }, // Col 2: First Name
    { wch: 6 },  // Col 3: Sex
    { wch: 6 },  // Col 4: Fed
    { wch: 10 }, // Col 5: Clubnumber
    { wch: 32 }, // Col 6: ClubName
    { wch: 12 }, // Col 7: Birthday
    { wch: 9 },  // Col 8: Rtg_Nat
    { wch: 11 }, // Col 9: Fide_No
    { wch: 9 },  // Col 10: Rtg_Int
    { wch: 8 },  // Col 11: Title
    { wch: 6 },  // Col 12: K
  ];

  XLSX.utils.book_append_sheet(wb, wsNat, 'Nat');

  // Sheet 2: Help from bundled template or fallback
  if (template.Sheets['Help']) {
    XLSX.utils.book_append_sheet(wb, template.Sheets['Help'], 'Help');
  } else {
    const wsHelp = XLSX.utils.aoa_to_sheet(HELP_SHEET_ROWS);
    wsHelp['!cols'] = [{ wch: 80 }];
    XLSX.utils.book_append_sheet(wb, wsHelp, 'Help');
  }

  return wb;
}

/**
 * Generates binary Excel 97-2003 BIFF8 (.xls) Blob
 */
export function generateNatXlsBlob(records: NatRecord[]): Blob {
  const wb = buildNatWorkbook(records);
  // bookType 'biff8' generates true binary Excel 97-2003 format required by Swiss-Manager
  const wbout = XLSX.write(wb, { bookType: 'biff8', type: 'array' });
  return new Blob([wbout], { type: 'application/octet-stream' });
}

/**
 * Generates modern .xlsx Blob
 */
export function generateNatXlsxBlob(records: NatRecord[]): Blob {
  const wb = buildNatWorkbook(records);
  const wbout = XLSX.write(wb, { bookType: 'xlsx', type: 'array' });
  return new Blob([wbout], {
    type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  });
}

/**
 * Triggers a client-side download of a Blob with maximum cross-browser resilience.
 * Supports Chrome, Edge, Firefox, Safari, and mobile browsers.
 */
export function downloadBlob(blob: Blob, filename: string) {
  // 1. IE / legacy Edge
  if (typeof (window.navigator as any)?.msSaveOrOpenBlob === 'function') {
    (window.navigator as any).msSaveOrOpenBlob(blob, filename);
    return;
  }

  // 2. Standard Blob URL download
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.style.display = 'none';
  a.href = url;
  a.download = filename;
  a.rel = 'noopener';

  if (typeof a.download === 'undefined') {
    a.target = '_blank';
  }

  document.body.appendChild(a);

  try {
    const clickEvent = new MouseEvent('click', {
      view: window,
      bubbles: true,
      cancelable: true,
    });
    a.dispatchEvent(clickEvent);
  } catch {
    a.click();
  }

  // Keep element in DOM briefly to allow browser event dispatch, then clean up
  setTimeout(() => {
    if (a.parentNode) {
      a.parentNode.removeChild(a);
    }
  }, 500);

  // Revoke URL after 60 seconds
  setTimeout(() => {
    try {
      URL.revokeObjectURL(url);
    } catch {
      // ignore
    }
  }, 60000);
}

// ---------------------------------------------------------------------------
// Native Android / iOS app (Capacitor) support
// The Android WebView cannot save blob: downloads or share files through the
// Web Share API, so inside the installed APK we use Capacitor plugins instead.
// ---------------------------------------------------------------------------

export type NatFileFormat = 'xls' | 'xlsx';

/** True when running inside the installed Capacitor app (APK), not a browser. */
export function isNativeApp(): boolean {
  return typeof window !== 'undefined' && !!(window as any).Capacitor?.isNativePlatform?.();
}

function toBookType(format: NatFileFormat): XLSX.BookType {
  return format === 'xls' ? 'biff8' : 'xlsx';
}

/** Writes base64 data to the app cache and opens the native share sheet. */
async function shareBase64Native(data: string, filename: string, recordCount: number): Promise<boolean> {
  const { Filesystem, Directory } = await import('@capacitor/filesystem');
  const { Share } = await import('@capacitor/share');

  const written = await Filesystem.writeFile({
    path: filename,
    data,
    directory: Directory.Cache,
  });

  try {
    await Share.share({
      title: 'Swiss-Manager NAT File',
      text: `Swiss-Manager NAT file containing ${recordCount} cleaned players.`,
      files: [written.uri],
      dialogTitle: 'Share or save NAT file',
    });
    return true;
  } catch (err: any) {
    // User closed the share sheet
    if (/cancel/i.test(String(err?.message ?? err))) return false;
    throw err;
  }
}

/**
 * Saves the workbook into the phone's Documents/SwissNat SL folder.
 * Falls back to the share sheet (Save to Drive / Files) if direct saving is not allowed.
 */
async function saveWorkbookNative(
  wb: XLSX.WorkBook,
  filename: string,
  format: NatFileFormat,
  recordCount: number
): Promise<'saved' | 'shared' | 'cancelled'> {
  const data = XLSX.write(wb, { bookType: toBookType(format), type: 'base64' }) as string;
  const { Filesystem, Directory } = await import('@capacitor/filesystem');

  try {
    try {
      const perm = await Filesystem.checkPermissions();
      if (perm.publicStorage !== 'granted') {
        await Filesystem.requestPermissions();
      }
    } catch {
      // Not required on newer Android versions
    }

    await Filesystem.writeFile({
      path: `SwissNat SL/${filename}`,
      data,
      directory: Directory.Documents,
      recursive: true,
    });
    return 'saved';
  } catch (err) {
    console.warn('Saving to Documents failed, opening share sheet instead:', err);
    const shared = await shareBase64Native(data, filename, recordCount);
    return shared ? 'shared' : 'cancelled';
  }
}

/**
 * Exports the NAT file and returns a user-facing status message.
 * Browser: normal file download. Installed app: saves to Documents/SwissNat SL.
 */
export async function exportNatFile(
  records: NatRecord[],
  filename: string,
  format: NatFileFormat = 'xls'
): Promise<string> {
  if (isNativeApp()) {
    const wb = buildNatWorkbook(records);
    const result = await saveWorkbookNative(wb, filename, format, records.length);
    if (result === 'saved') return `Saved "${filename}" to Documents/SwissNat SL (${records.length} players)`;
    if (result === 'shared') return `"${filename}" ready (${records.length} players)`;
    return 'Export cancelled';
  }

  if (format === 'xls') {
    downloadNatXls(records, filename);
  } else {
    downloadNatXlsx(records, filename);
  }
  return `Downloaded "${filename}" (${records.length} players)`;
}

/**
 * Downloads Swiss-Manager compatible Excel 97-2003 BIFF8 (.xls) file
 * Tries SheetJS XLSX.writeFile first, then falls back to Blob download
 */
export function downloadNatXls(
  records: NatRecord[],
  filename = 'Nat_File_Master.xls'
): void {
  const wb = buildNatWorkbook(records);

  // Installed app (APK): blob downloads don't work in the WebView
  if (isNativeApp()) {
    void saveWorkbookNative(wb, filename, 'xls', records.length).catch(err =>
      console.error('Native .xls save failed:', err)
    );
    return;
  }

  // Attempt 1: SheetJS official writeFile
  try {
    if (typeof XLSX.writeFile === 'function') {
      XLSX.writeFile(wb, filename, { bookType: 'biff8' });
      return;
    }
  } catch (err) {
    console.warn('XLSX.writeFile failed, falling back to Blob download:', err);
  }

  // Attempt 2: Binary Blob download with application/octet-stream
  const wbout = XLSX.write(wb, { bookType: 'biff8', type: 'array' });
  const blob = new Blob([wbout], { type: 'application/octet-stream' });
  downloadBlob(blob, filename);
}

